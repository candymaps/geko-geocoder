//! Country packs read at run time (PROJECT.md §2.4): what the engine knows about a country is
//! data in a folder, not code compiled into the binary.
//!
//! ```text
//! <packs>/<country>/
//!   pack.toml              country, languages, postcode format
//!   data/street-types.toml
//!   data/words.toml
//!   data/equivalences.txt
//!   data/admin-levels.toml
//!   data/regions.toml      optional: partitions and the regions that group them
//!   data/region-boxes.tsv  optional, generated: a box that holds each partition
//!   sources/<source>.toml  optional: what a source needs to know about the country
//! ```
//!
//! A pack is loaded the first time its country is asked for, and kept for the life of the process.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock};

use geko_core::country::{CountryCode, RegionCode};
use geko_core::geo::{BBox, Coord};
use geko_core::regions::{Region, Regions};
use geko_core::{GekoError, Result};
use serde::Deserialize;
use sha2::{Digest, Sha256};
use text_rules::{Pack, RulesNormalizer, RulesParser};

pub mod registry;
pub mod signature;

const TEXT_FILES: [&str; 5] =
    ["pack.toml", "data/street-types.toml", "data/words.toml", "data/equivalences.txt", "data/admin-levels.toml"];
const REGIONS_FILE: &str = "data/regions.toml";
/// Generated by `geko-eval region-boxes` from the boundaries of a build: one line per region,
/// `<code>\t<min lon>\t<min lat>\t<max lon>\t<max lat>`, in degrees.
pub const BOXES_FILE: &str = "data/region-boxes.tsv";
const SOURCES_DIR: &str = "sources";

pub struct CountryPack {
    pub country: CountryCode,
    pub text: &'static Pack,
    pub regions: Regions,
    /// What each source needs to know about the country (`sources/<source>.toml`), by source. A
    /// file with a `kind` declares a source of its own, for the generic provider of that kind.
    pub sources: BTreeMap<String, toml::Table>,
    /// A hash of each file of `sources/`, by source: the staging of a source reruns when its file
    /// changes, and no other stage does.
    pub source_codes: BTreeMap<String, String>,
    /// A hash of the text rules and the regions of the pack: the stages that use them rerun when
    /// they change.
    pub code: String,
    /// The folder it was read from, and the files of it that geko reads, relative to it.
    pub dir: PathBuf,
    pub files: Vec<String>,
}

impl CountryPack {
    pub fn load(dir: &Path) -> Result<Self> {
        let read = |name: &str| {
            std::fs::read_to_string(dir.join(name))
                .map_err(|e| GekoError::Config(format!("country pack {}: cannot read {name}: {e}", dir.display())))
        };
        let mut hasher = Sha256::new();
        let mut hash = |name: &str, text: &str| {
            for part in [name, text] {
                hasher.update((part.len() as u64).to_le_bytes());
                hasher.update(part.as_bytes());
            }
        };
        let texts = TEXT_FILES.map(|name| read(name).inspect(|text| hash(name, text)));
        let [pack, street_types, words, equivalences, admin_levels] = texts;
        let text = Pack::from_toml(&pack?, &street_types?, &words?, &equivalences?, &admin_levels?)
            .map_err(|e| GekoError::Config(format!("country pack {}: {e}", dir.display())))?;
        let country = text.country;
        // The boxes only choose what a source downloads by area: not part of `code`, so that
        // regenerating them reruns no stage that reads the text rules.
        let boxes = match dir.join(BOXES_FILE).exists() {
            true => Some(read(BOXES_FILE)?),
            false => None,
        };
        let regions = match dir.join(REGIONS_FILE).exists() {
            true => {
                let regions = read(REGIONS_FILE)?;
                hash(REGIONS_FILE, &regions);
                parse_regions(country, &regions, boxes.as_deref())
                    .map_err(|e| GekoError::Config(format!("country pack {}: {e}", dir.display())))?
            }
            false if boxes.is_some() => {
                return Err(GekoError::Config(format!("country pack {}: {BOXES_FILE} without {REGIONS_FILE}", dir.display())));
            }
            false => Regions::default(),
        };
        let mut files: Vec<String> = TEXT_FILES.iter().map(|f| f.to_string()).collect();
        for optional in [REGIONS_FILE, BOXES_FILE] {
            if dir.join(optional).exists() {
                files.push(optional.into());
            }
        }
        if dir.join(signature::SIGNATURE_FILE).is_file() {
            files.push(signature::SIGNATURE_FILE.into());
        }
        let mut sources = BTreeMap::new();
        let mut source_codes = BTreeMap::new();
        let mut names: Vec<PathBuf> = match std::fs::read_dir(dir.join(SOURCES_DIR)) {
            Ok(entries) => entries.map(|e| e.map(|e| e.path())).collect::<std::io::Result<_>>()?,
            Err(_) => Vec::new(),
        };
        names.sort();
        for path in names.into_iter().filter(|p| p.extension().is_some_and(|e| e == "toml")) {
            let name = format!("{SOURCES_DIR}/{}", path.file_name().unwrap_or_default().to_string_lossy());
            let source = path.file_stem().unwrap_or_default().to_string_lossy().into_owned();
            let text = read(&name)?;
            let table = text
                .parse::<toml::Table>()
                .map_err(|e| GekoError::Config(format!("country pack {}: {name}: {e}", dir.display())))?;
            source_codes.insert(source.clone(), hex(&Sha256::digest(text.as_bytes())));
            sources.insert(source, table);
            files.push(name);
        }
        files.sort();
        let code = hex(&hasher.finalize());
        Ok(Self { country, text: Box::leak(Box::new(text)), regions, sources, source_codes, code, dir: dir.to_path_buf(), files })
    }

    /// Copies the files of the pack that geko reads to `dest`, emptied first: a bundle carries the
    /// pack it was built with, so that `serve` reads the same rules on any machine.
    pub fn copy_to(&self, dest: &Path) -> Result<()> {
        if dest.exists() {
            std::fs::remove_dir_all(dest)?;
        }
        for file in &self.files {
            let to = dest.join(file);
            std::fs::create_dir_all(to.parent().expect("a file has a folder"))?;
            std::fs::copy(self.dir.join(file), to)?;
        }
        Ok(())
    }

    pub fn normalizer(&self) -> RulesNormalizer {
        RulesNormalizer::new(self.text)
    }

    pub fn parser(&self) -> RulesParser {
        RulesParser::new(self.normalizer())
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RegionsFile {
    regions: Vec<RegionEntry>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RegionEntry {
    code: String,
    name: String,
    #[serde(default)]
    parent: Option<String>,
    #[serde(default)]
    attributes: BTreeMap<String, String>,
}

fn parse_regions(country: CountryCode, text: &str, boxes: Option<&str>) -> Result<Regions> {
    let file: RegionsFile = toml::from_str(text).map_err(|e| GekoError::Config(format!("{REGIONS_FILE}: {e}")))?;
    let code = |c: &str| RegionCode::new(c).map_err(|e| GekoError::Config(format!("{REGIONS_FILE}: {e}")));
    let mut regions = file
        .regions
        .into_iter()
        .map(|r| {
            Ok(Region {
                code: code(&r.code)?,
                name: r.name,
                parent: r.parent.as_deref().map(code).transpose()?,
                attributes: r.attributes,
                bbox: None,
            })
        })
        .collect::<Result<Vec<_>>>()?;
    for (code, bbox) in parse_boxes(boxes.unwrap_or_default())? {
        let region = regions
            .iter_mut()
            .find(|r| r.code.as_str() == code)
            .ok_or_else(|| GekoError::Config(format!("{BOXES_FILE}: {code} is not in {REGIONS_FILE}")))?;
        region.bbox = Some(bbox);
    }
    Regions::new(country, regions)
}

/// The lines of `data/region-boxes.tsv`; `#` starts a comment.
fn parse_boxes(text: &str) -> Result<Vec<(String, BBox)>> {
    let mut boxes = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        let invalid = |why: String| GekoError::Config(format!("{BOXES_FILE}:{}: {why}", n + 1));
        let fields: Vec<&str> = line.split('\t').collect();
        let [code, values @ ..] = fields.as_slice() else { unreachable!("split yields at least one field") };
        let values = values.iter().map(|v| v.parse::<f64>().map_err(|e| invalid(format!("`{v}`: {e}")))).collect::<Result<Vec<_>>>()?;
        let [min_lon, min_lat, max_lon, max_lat] = values[..] else {
            return Err(invalid("expected a code and four numbers: min lon, min lat, max lon, max lat".into()));
        };
        let corner = |lat, lon| Coord::from_degrees(lat, lon).map_err(|e| invalid(e.to_string()));
        let bbox = BBox::new(corner(min_lat, min_lon)?, corner(max_lat, max_lon)?).map_err(|e| invalid(e.to_string()))?;
        boxes.push(((*code).to_owned(), bbox));
    }
    Ok(boxes)
}

static DIR: OnceLock<PathBuf> = OnceLock::new();
static LOADED: Mutex<BTreeMap<CountryCode, &'static CountryPack>> = Mutex::new(BTreeMap::new());

/// Sets the folder that holds a subfolder per country (`es/`, `lu/`…). Set once, at start-up.
pub fn init(dir: PathBuf) {
    let _ = DIR.set(dir);
}

/// The pack of `country`, loaded from the folder given to `init` the first time it is asked for.
pub fn get(country: CountryCode) -> Result<&'static CountryPack> {
    let dir = DIR.get().ok_or_else(|| GekoError::Config("the folder of the country packs is not set".into()))?;
    load_cached(country, dir)
}

/// Whether the pack of some country in the folder given to `init` has `sources/<name>.toml`,
/// loaded or not: a `[sources.<name>]` section for a country outside the scope is then no typo.
pub fn declares(name: &str) -> bool {
    let Some(dir) = DIR.get() else { return false };
    let Ok(entries) = std::fs::read_dir(dir) else { return false };
    entries.filter_map(|e| e.ok()).any(|e| e.path().join(SOURCES_DIR).join(format!("{name}.toml")).is_file())
}

/// The pack of `country` as it is in this repository (`countries/<country>/`), for tests and the
/// development tools.
pub fn repo(country: &str) -> &'static CountryPack {
    let country = CountryCode::new(country).expect("a valid country code");
    load_cached(country, &Path::new(env!("CARGO_MANIFEST_DIR")).join("../../countries"))
        .unwrap_or_else(|e| panic!("the pack of {country} in the repository: {e}"))
}

fn load_cached(country: CountryCode, dir: &Path) -> Result<&'static CountryPack> {
    let mut loaded = LOADED.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(pack) = loaded.get(&country) {
        return Ok(pack);
    }
    let path = dir.join(country.as_str().to_lowercase());
    if !path.is_dir() {
        return Err(GekoError::Config(format!("no country pack for {country}: {} does not exist", path.display())));
    }
    let pack: &'static CountryPack = Box::leak(Box::new(CountryPack::load(&path)?));
    if pack.country != country {
        return Err(GekoError::Config(format!("{}: pack.toml says {}, not {country}", path.display(), pack.country)));
    }
    loaded.insert(country, pack);
    Ok(pack)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_packs_of_the_repository_load() {
        let es = repo("ES");
        assert_eq!(es.regions.partitions().count(), 52);
        assert!(es.sources.contains_key("osm") && es.sources["cartociudad"].contains_key("kind"));
        assert_eq!(es.source_codes.len(), es.sources.len());
        let lu = repo("LU");
        assert!(lu.regions.is_empty() && lu.sources.is_empty());
        assert_ne!(es.code, lu.code);
        assert!(es.files.contains(&"data/regions.toml".to_owned()) && es.files.contains(&"sources/cartociudad.toml".to_owned()));
        let tmp = tempfile::tempdir().unwrap();
        es.copy_to(&tmp.path().join("pack")).unwrap();
        let copy = CountryPack::load(&tmp.path().join("pack")).unwrap();
        assert_eq!((copy.code, copy.files), (es.code.clone(), es.files.clone()));
    }

    #[test]
    fn every_partition_of_spain_has_a_box() {
        let es = repo("ES");
        assert!(es.files.contains(&BOXES_FILE.to_owned()));
        let pm = es.regions.partitions().find(|r| r.code.as_str() == "ES-PM").and_then(|r| r.bbox).expect("a box for ES-PM");
        assert!(pm.contains(Coord::from_degrees(39.57, 2.65).unwrap()), "Palma");
        assert!(es.regions.partitions().all(|r| r.bbox.is_some()));
        assert!(parse_boxes("ES-XX\t1\t2\t3\t4\n").is_ok() && parse_boxes("ES-PM\t1\t2\t3\n").is_err());
        let regions = std::fs::read_to_string(es.dir.join(REGIONS_FILE)).unwrap();
        let err = parse_regions(es.country, &regions, Some("ES-XX\t1\t2\t3\t4\n")).unwrap_err();
        assert!(err.to_string().contains("ES-XX is not in"), "{err}");
    }

    #[test]
    fn a_pack_needs_a_version() {
        let es = repo("ES");
        assert!(es.text.version >= 1);
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("es");
        es.copy_to(&dir).unwrap();
        let manifest = std::fs::read_to_string(dir.join("pack.toml")).unwrap();
        let line = format!("version = {}\n", es.text.version);
        for replaced in ["", "version = 0\n"] {
            std::fs::write(dir.join("pack.toml"), manifest.replace(&line, replaced)).unwrap();
            let err = CountryPack::load(&dir).err().expect("refused");
            assert!(err.to_string().contains("version"), "{err}");
        }
    }

    #[test]
    fn a_missing_pack_is_an_error() {
        let dir = tempfile::tempdir().unwrap();
        init(dir.path().to_path_buf());
        assert!(get(CountryCode::new("FR").unwrap()).is_err());
        std::fs::create_dir_all(dir.path().join("es/sources")).unwrap();
        std::fs::write(dir.path().join("es/sources/cartociudad.toml"), "").unwrap();
        assert!(declares("cartociudad") && !declares("osmm"));
    }
}
