//! The box of each partition of a country pack (`data/region-boxes.tsv`), from the boundaries
//! of a build: the administrative areas of the canonical dataset that carry the ISO 3166-2 code
//! of the partition. A source that downloads by area fetches only what the partitions of the
//! scope need (PROJECT.md 17, item 46).

use std::collections::BTreeMap;
use std::fs::File;
use std::path::Path;

use anyhow::{Context, Result, bail};
use arrow_array::Array;
use arrow_array::cast::AsArray;
use geko_country_pack::CountryPack;
use geko_geom::BBox;
use geko_geom::wkb::{self, Geometry};
use parquet::arrow::arrow_reader::ParquetRecordBatchReaderBuilder;

const SCALE: f64 = 1e7;

/// The boxes of the partitions of the pack in `pack`, from `canonical` (`<data>/canonical/<COUNTRY>`),
/// each widened by `margin` degrees and rounded outwards to 1e-4: what lies on a boundary, a
/// pier or a point a source places a little off, still falls inside.
pub fn region_boxes(canonical: &Path, pack: &Path, margin: f64) -> Result<String> {
    let pack = CountryPack::load(pack)?;
    let partitions: Vec<String> = pack.regions.partitions().map(|r| r.code.as_str().to_owned()).collect();
    if partitions.is_empty() {
        bail!("the pack of {} lists no regions: its partition is the whole country", pack.country);
    }
    let path = canonical.join("places.parquet");
    let file = File::open(&path).with_context(|| path.display().to_string())?;
    let mut found: BTreeMap<String, BBox> = BTreeMap::new();
    for batch in ParquetRecordBatchReaderBuilder::try_new(file)?.with_batch_size(4_096).build()? {
        let batch = batch?;
        let column = |name: &str| batch.column_by_name(name).with_context(|| format!("{}: no column {name}", path.display()));
        let codes = column("iso3166_2")?.as_string::<i32>().clone();
        let geoms = column("geom")?.as_binary::<i32>().clone();
        for i in 0..batch.num_rows() {
            if !codes.is_valid(i) || !geoms.is_valid(i) || !partitions.iter().any(|p| p == codes.value(i)) {
                continue;
            }
            let Some(Geometry::Polygons(polygons)) = wkb::parse(geoms.value(i)) else { continue };
            let bbox = BBox::of(polygons.iter().flatten().flatten().copied());
            found
                .entry(codes.value(i).to_owned())
                .and_modify(|b| *b = BBox::of([b.min, b.max, bbox.min, bbox.max]))
                .or_insert(bbox);
        }
    }
    let missing: Vec<&str> = partitions.iter().filter(|p| !found.contains_key(*p)).map(String::as_str).collect();
    if !missing.is_empty() {
        bail!("{}: no boundary with the code of {}", path.display(), missing.join(", "));
    }
    let mut out = format!(
        "# A box that holds each partition, in degrees: code, min lon, min lat, max lon, max lat.\n\
         # Generated by `geko-eval region-boxes` from the boundaries of a build, widened by {margin}°.\n\
         # A source that downloads by area (Overture) fetches only what the partitions of the scope need.\n"
    );
    let down = |v: i32| ((v as f64 / SCALE - margin) * 1e4).floor() / 1e4;
    let up = |v: i32| ((v as f64 / SCALE + margin) * 1e4).ceil() / 1e4;
    for code in &partitions {
        let b = found[code];
        let lat = |v: f64| v.clamp(-90.0, 90.0);
        let lon = |v: f64| v.clamp(-180.0, 180.0);
        out.push_str(&format!("{code}\t{}\t{}\t{}\t{}\n", lon(down(b.min.0)), lat(down(b.min.1)), lon(up(b.max.0)), lat(up(b.max.1))));
    }
    Ok(out)
}
